let currentLang = localStorage.getItem("siteLang") || "zh";

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("siteLang", lang);
  applyLang();
  toggleLangMenu();
}

function applyLang() {
  const t = langData[currentLang];
  document.querySelectorAll("[data-lang]").forEach(el => {
    const k = el.getAttribute("data-lang");
    if (t[k]) el.innerText = t[k];
  });
  const inp = document.getElementById("searchInput");
  if (inp) inp.placeholder = t.searchPlaceholder;
}

function toggleLangMenu() {
  const m = document.getElementById("langMenu");
  m.style.display = m.style.display === "block" ? "none" : "block";
}

document.addEventListener("click", e => {
  const b = document.getElementById("langBtn");
  const m = document.getElementById("langMenu");
  if (b && m && !b.contains(e.target) && !m.contains(e.target)) m.style.display = "none";
});

window.onload = applyLang;